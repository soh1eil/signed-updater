package manifest

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/soh1eil/signed-updater/signing"
)

var update = flag.Bool("update", false, "rewrite testdata/interop.json")

// The key below is a published TEST key. It exists only to produce fixtures
// that the Dart package verifies; never use it for anything real.
const (
	interopSeedHex = "2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a2a"
	interopContext = "interop-test-v1"
)

type interopFile struct {
	Comment   string        `json:"comment"`
	Context   string        `json:"context"`
	PublicKey string        `json:"public_key"`
	OtherKey  string        `json:"other_public_key"`
	Artifacts []interopBlob `json:"artifacts"`
	Messages  []interopMsg  `json:"messages"`
	Manifest  Manifest      `json:"manifest"`
	URLs      []interopURL  `json:"urls"`
	Versions  []interopCmp  `json:"versions"`
}

type interopBlob struct {
	Name   string `json:"name"`
	Base64 string `json:"base64"`
	SHA256 string `json:"sha256"`
}

type interopMsg struct {
	Name      string `json:"name"`
	Message   string `json:"message"`
	Signature string `json:"signature"`
	Entry     Entry  `json:"entry"`
}

type interopURL struct {
	URL   string `json:"url"`
	Valid bool   `json:"valid"`
}

type interopCmp struct {
	A, B string
	Want int
}

func buildInterop(t *testing.T) []byte {
	t.Helper()
	seed, _ := hex.DecodeString(interopSeedHex)
	key := ed25519.NewKeyFromSeed(seed)
	other := ed25519.NewKeyFromSeed(make([]byte, 32))
	f := interopFile{
		Comment:   "Generated by `go test ./manifest -run Interop -update`. Test key only.",
		Context:   interopContext,
		PublicKey: hex.EncodeToString(key.Public().(ed25519.PublicKey)),
		OtherKey:  hex.EncodeToString(other.Public().(ed25519.PublicKey)),
	}
	blobs := map[string][]byte{"win-1.0.0.bin": []byte("windows one"), "win-1.1.0.bin": []byte("windows one-one\n"), "lin-1.1.0.bin": []byte("linux one-one")}
	for _, name := range []string{"win-1.0.0.bin", "win-1.1.0.bin", "lin-1.1.0.bin"} {
		sum := sha256.Sum256(blobs[name])
		f.Artifacts = append(f.Artifacts, interopBlob{name, base64Std(blobs[name]), hex.EncodeToString(sum[:])})
	}
	mk := func(version string, build int64, platform, url, blob, notes string) Entry {
		sum := sha256.Sum256(blobs[blob])
		e := Entry{Version: version, Build: build, Platform: platform, URL: url,
			SHA256: hex.EncodeToString(sum[:]), Size: int64(len(blobs[blob])), Notes: notes}
		sig, err := signing.Sign(key, interopContext, e.Claims())
		if err != nil {
			t.Fatal(err)
		}
		e.Sig = sig
		return e
	}
	entries := []Entry{
		mk("1.0.0", 10, "windows", "files/win-1.0.0.bin", "win-1.0.0.bin", ""),
		mk("1.1.0", 11, "windows", "files/win-1.1.0.bin", "win-1.1.0.bin", "نسخه ۱٫۱ — fixes\nsecond line \u2713"),
		mk("1.1.0", 11, "linux", "files/lin-1.1.0.bin", "lin-1.1.0.bin", "linux notes"),
	}
	for i, e := range entries {
		m, err := signing.Message(interopContext, e.Claims())
		if err != nil {
			t.Fatal(err)
		}
		f.Messages = append(f.Messages, interopMsg{Name: []string{"empty-notes", "unicode-notes", "linux"}[i], Message: string(m), Signature: e.Sig, Entry: e})
	}
	f.Manifest = Manifest{Schema: 1, Releases: entries}
	for _, u := range []string{"files/a.bin", "a.bin?x=1", "a/b%20c", "../x", "/abs", "//h/x", "https://h/x", "a/%2e%2e/b", "a\\b", "a/./b", "C:/x", "a//b", "a/%2F/b", "a#f", "a b"} {
		f.URLs = append(f.URLs, interopURL{u, signing.ValidRelativeURL(u) == nil})
	}
	for _, c := range []interopCmp{{"1.0.0", "1.0.0", 0}, {"1.2.10", "1.2.9", 1}, {"1.9", "1.10", -1}, {"1.0", "1.0.0", 0}, {"2", "1.99.99", 1}} {
		f.Versions = append(f.Versions, c)
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

func TestInterop(t *testing.T) {
	path := filepath.Join("..", "testdata", "interop.json")
	want := buildInterop(t)
	if *update {
		if err := os.WriteFile(path, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if string(got) != string(want) {
		t.Fatal("testdata/interop.json is stale; run: go test ./manifest -run Interop -update")
	}
	if !strings.Contains(string(got), interopContext) {
		t.Fatal("context missing")
	}
}

func base64Std(b []byte) string { return base64.StdEncoding.EncodeToString(b) }
